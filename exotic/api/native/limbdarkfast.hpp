// F = 1 - (O_0 - sum_j w_j O_Sj) / (pi - sum_j w_j N_j), from the occulted
// flux occ[k] of each generator
inline double flux_from_occ(const double* occ, const double* w,
                            const LawData& L) {
    double blocked = occ[0], norm = PI;
    for (int j = 0; j < L.n_w; ++j) {
        double s = 0.0;
        for (int k = 0; k < 3 + L.K; ++k) s += L.G[j][k] * occ[k];
        blocked -= w[j] * s;
        norm -= w[j] * L.norms[j];
    }
    return 1.0 - blocked / norm;
}

// ===========================================================================
// spherical planet
// ===========================================================================

// 16 x (area of the triangle with sides 1, z, r)^2, sorted (Kahan) form;
// negative when no such triangle exists
inline double kite_sqarea(double z, double r) {
    double a = std::max(z, r), c = std::min(z, r);
    double b = std::min(a, 1.0);
    a = std::max(a, 1.0);
    double bb = std::max(b, c), cc = std::min(b, c);
    return (a + (bb + cc)) * (cc - (a - bb)) * (cc + (a - bb)) * (a + (bb - cc));
}

// occulted flux of [mu^0, mu^2, mu^4, P_eps...] for a circle of radius r
// at separation z
inline void sphere_occ(double z, double r, const LawData& L, double* occ) {
    z = std::fabs(z);
    for (int k = 0; k < 3 + L.K; ++k) occ[k] = 0.0;
    if (z >= 1.0 + r) return;
    // r^2 - 1 is factored: z^2 is lost against it when r = 1 and z is small
    const double r2 = r * r, z2 = z * z, rm1 = (r - 1.0) * (r + 1.0), alpha = -rm1 - z2;
    const double sqarea = kite_sqarea(z, r);

    if (z <= 1.0 - r) {                       // planet wholly on the disc
        const double s0 = -PI * r2;
        const double s2 = TWO_PI * r2 * (r2 + 2.0 * z2 - 1.0);
        const double M0 = PI, M2 = PI * alpha;
        const double M4 = (6.0 * alpha * M2 + 2.0 * sqarea * M0) / 4.0;
        const double s4 = -(2.0 * r2 * M4 - (2.0 / 3.0) * (alpha * M4 + sqarea * M2));
        occ[0] = -s0;
        occ[1] = -(0.5 * s0 + 0.25 * s2);
        occ[2] = -(s0 / 3.0 + s2 / 6.0 + s4 / 6.0);
        const double A = std::max((r + 1.0 - z) * (1.0 - r + z), TINY);
        const double Bp = ((1.0 - std::max(z, r)) - std::min(z, r)) * (1.0 + z + r);
        for (int k = 0; k < L.K; ++k) {
            const double e = L.eps[k], p = 1.0 + e;
            const double K = p + r2 - z2;
            const double sqQ = std::sqrt((e + A) * (e + Bp));
            occ[3 + k] = TWO_PI * r2 / (sqQ * (K + sqQ));
        }
        return;
    }

    // partial overlap (or, for r > 1, total occultation: kite = 0 there,
    // and every term lands on its full-disc value)
    const bool tot = z <= r - 1.0;
    const double A = std::max((r + 1.0 - z) * (1.0 - r + z), TINY);  // 1-(z-r)^2
    // 1 - (z+r)^2, the larger of z and r taken from 1 first (exactly, when it
    // is near 1), so that the smaller is not rounded against 1
    const double Bp = ((1.0 - std::max(z, r)) - std::min(z, r)) * (1.0 + z + r);
    // sqarea > 0 in the lens, to a few ulps; the floor only keeps kite^2 representable
    const double kite = tot ? 0.0 : std::sqrt(std::max(sqarea, TINY));
    const double kap0 = std::atan2(kite, rm1 + z2);        // angle at the planet
    const double kap1 = std::atan2(kite, z2 - rm1);        // angle at the star

    const double s0 = -(kap1 + r2 * kap0 - 0.5 * kite);
    const double eta2 = r2 * (r2 + 2.0 * z2);
    const double s2 = 2.0 * s0 + 2.0 * (kap1 + eta2 * kap0
                                        - 0.25 * kite * (1.0 + 5.0 * r2 + z2));
    const double M0 = kap0, M2 = kap0 * alpha + kite;
    const double M4 = (6.0 * alpha * M2 + 2.0 * sqarea * M0) / 4.0;
    const double s4 = -(2.0 * r2 * M4 - (2.0 / 3.0) * (alpha * M4 + sqarea * M2));
    occ[0] = -s0;
    occ[1] = -(0.5 * s0 + 0.25 * s2);
    occ[2] = -(s0 / 3.0 + s2 / 6.0 + s4 / 6.0);

    // the smaller of A and -Bp is taken from kite^2 = A (-Bp), exactly
    double nBp;
    if (!tot && A >= -Bp) nBp = kite * kite / A;
    else nBp = (-Bp > 0.0) ? -Bp : kite * kite / A;
    for (int k = 0; k < L.K; ++k) {
        const double e = L.eps[k], p = 1.0 + e;
        const double K = p + r2 - z2;
        const double Q = (e + A) * (e + Bp);
        // J = int_{-kap0}^{kap0} dpsi / (p - z^2 - r^2 + 2 z r cos psi)
        const double apb = e + A;
        const double U = apb * nBp;
        const double ratio = (e + Bp) / nBp;
        const double y = ratio * kite * kite / U;
        double J;
        if (y > Y_SW) {
            J = 4.0 / std::sqrt(Q) * std::atan2(kite * std::sqrt(ratio), std::sqrt(U));
        } else if (y < -Y_SW) {
            J = 4.0 / std::sqrt(-Q)
                * std::log((std::sqrt(U) + kite * std::sqrt(-ratio))
                           / (2.0 * std::sqrt(std::max(z * r * e, TINY))));
        } else {                               // across Q = 0: a series
            const double T = kite / nBp;       // tan(kap0 / 2)
            const double y2 = y * y;
            const double G = 1.0 - y / 3.0 + y2 / 5.0 - y * y2 / 7.0
                             + y2 * y2 / 9.0 - y * y2 * y2 / 11.0;
            J = 4.0 * T * G / apb;
        }
        occ[3 + k] = kap1 / (p * e) + (K * J - 2.0 * kap0) / (4.0 * p);
    }
}

// ===========================================================================
// oblate planet: the ellipse x = x0 + a cos phi, y = y0 + b sin phi
// ===========================================================================
//
// With z = e^{i phi}, s(phi) = x^2 + y^2 = S0 + 2 Re(S1 z) + 2 S2 cos 2 phi
// and (x dy - y dx)/dphi = K0 + 2 Re(K1 z). The points where s = p are the
// roots of the self-inversive quartic
//     D(z) = S2 z^4 + S1 z^3 + (S0 - p) z^2 + conj(S1) z + S2.

struct Ellipse {
    double S0, S2, K0;
    cplx S1, K1;
    Ellipse(double x0, double y0, double a, double b)
        : S0(x0 * x0 + y0 * y0 + 0.5 * (a * a + b * b)),
          S2(0.25 * (a * a - b * b)),
          K0(a * b),
          S1(a * x0, -b * y0),
          K1(0.5 * b * x0, -0.5 * a * y0) {}
    cplx D(cplx z, double p) const {
        return (((S2 * z + S1) * z + (S0 - p)) * z + std::conj(S1)) * z + S2;
    }
    cplx dD(cplx z, double p) const {
        return ((4.0 * S2 * z + 3.0 * S1) * z + 2.0 * (S0 - p)) * z + std::conj(S1);
    }
    cplx N(cplx z) const { return std::conj(K1) + K0 * z + K1 * z * z; }
};

inline bool finite(cplx z) {
    return std::isfinite(z.real()) && std::isfinite(z.imag());
}

// ---- the quartic's roots: a balanced, shifted 4x4 QR, then Aberth --------

inline void givens(cplx x, cplx y, double& c, cplx& s) {
    const double xa = std::abs(x);
    const double rho = std::sqrt(xa * xa + std::norm(y));
    const cplx ph = xa > 0.0 ? x / xa : cplx(1.0, 0.0);
    if (rho > 0.0) {
        c = xa / rho;
        s = ph * std::conj(y) / rho;
    } else {
        c = 1.0;
        s = 0.0;
    }
}

// the eigenvalue of [[a, b], [c, d]] nearer d
inline cplx wilkinson(cplx a, cplx b, cplx c, cplx d) {
    const cplx h = 0.5 * (a - d);
    const cplx disc = std::sqrt(h * h + b * c);
    const cplx den = std::abs(h + disc) >= std::abs(h - disc) ? h + disc : h - disc;
    return den != 0.0 ? d - b * c / den : d;
}

// one shifted QR step on the leading m x m block of H
inline void qr_sweep(cplx H[4][4], int m) {
    const cplx sig = wilkinson(H[m - 2][m - 2], H[m - 2][m - 1],
                               H[m - 1][m - 2], H[m - 1][m - 1]);
    for (int i = 0; i < m; ++i) H[i][i] -= sig;
    double cs[3];
    cplx sn[3];
    for (int k = 0; k < m - 1; ++k) {
        givens(H[k][k], H[k + 1][k], cs[k], sn[k]);
        for (int j = k; j < m; ++j) {
            const cplx x = H[k][j], y = H[k + 1][j];
            H[k][j] = cs[k] * x + sn[k] * y;
            H[k + 1][j] = cs[k] * y - std::conj(sn[k]) * x;
        }
    }
    for (int k = 0; k < m - 1; ++k) {
        for (int i = 0; i <= std::min(k + 2, m - 1); ++i) {
            const cplx x = H[i][k], y = H[i][k + 1];
            H[i][k] = cs[k] * x + std::conj(sn[k]) * y;
            H[i][k + 1] = cs[k] * y - sn[k] * x;
        }
    }
    for (int i = 0; i < m; ++i) H[i][i] += sig;
}

// eigenvalues of D's companion matrix
inline void qr_seeds(const Ellipse& E, double p, cplx z[4]) {
    cplx H[4][4];
    for (int i = 0; i < 4; ++i)
        for (int j = 0; j < 4; ++j) H[i][j] = 0.0;
    const double inv = 1.0 / E.S2;
    H[0][0] = -E.S1 * inv;
    H[0][1] = -(E.S0 - p) * inv;
    H[0][2] = -std::conj(E.S1) * inv;
    H[0][3] = -1.0;
    H[1][0] = H[2][1] = H[3][2] = 1.0;
    for (int it = 0; it < QR_BALANCE; ++it) {       // diagonal similarity
        for (int i = 0; i < 4; ++i) {
            double col = 0.0, row = 0.0;
            for (int j = 0; j < 4; ++j) {
                if (j == i) continue;
                col += std::abs(H[j][i]);
                row += std::abs(H[i][j]);
            }
            const double f = (col > 0.0 && row > 0.0) ? std::sqrt(row / col) : 1.0;
            for (int j = 0; j < 4; ++j) {
                H[j][i] *= f;
                H[i][j] /= f;
            }
        }
    }
    for (int it = 0; it < QR_SWEEPS4; ++it) qr_sweep(H, 4);
    for (int it = 0; it < QR_SWEEPS3; ++it) qr_sweep(H, 3);
    const cplx a = H[0][0], b = H[0][1], c = H[1][0], d = H[1][1];
    const cplx h = 0.5 * (a - d);
    const cplx disc = std::sqrt(h * h + b * c);
    const cplx mid = 0.5 * (a + d);
    z[0] = mid + disc;
    z[1] = mid - disc;
    z[2] = H[2][2];
    z[3] = H[3][3];
}

// the four roots of D at level p: eigenvalue seeds, then Aberth iterations
// (at most N_ABERTH, stopping once every correction is at rounding) and two
// Newton polishes; a correction that is not finite is skipped
inline void roots(const Ellipse& E, double p, cplx z[4]) {
    qr_seeds(E, p, z);
    for (int it = 0; it < N_ABERTH; ++it) {
        cplx rat[4];
        for (int i = 0; i < 4; ++i) rat[i] = E.D(z[i], p) / E.dD(z[i], p);
        cplx nz[4];
        bool done = true;
        for (int i = 0; i < 4; ++i) {
            cplx s = 0.0;
            for (int j = 0; j < 4; ++j)
                if (j != i && z[i] != z[j]) s += 1.0 / (z[i] - z[j]);
            const cplx step = rat[i] / (1.0 - rat[i] * s);
            nz[i] = finite(step) ? z[i] - step : z[i];
            if (finite(step) && std::abs(step) > 4.0 * EPS * std::abs(z[i])) done = false;
        }
        for (int i = 0; i < 4; ++i) z[i] = nz[i];
        if (done) break;
    }
    for (int it = 0; it < 2; ++it)
        for (int i = 0; i < 4; ++i) {
            const cplx nw = z[i] - E.D(z[i], p) / E.dD(z[i], p);
            if (finite(nw)) z[i] = nw;
        }
}

// ---- limb crossings and the arcs ------------------------------------------

inline double mod2pi(double t) { return t - TWO_PI * std::floor(t / TWO_PI); }

inline void g_dg(double phi, double x0, double y0, double a, double b,
                 double& g, double& dg) {
    const double s = std::sin(phi), c = std::cos(phi);
    const double x = x0 + a * c, y = y0 + b * s;
    g = x * x + y * y - 1.0;
    dg = 2.0 * (-x * a * s + y * b * c);
}

// number of limb crossings, and the first two (phi_a <= phi_b) on the
// ellipse parameter; crossings closer than PAIR_TOL are a tangency and are
// dropped together
inline int crossings(double x0, double y0, double a, double b,
                     double& phi_a, double& phi_b) {
    const Ellipse E(x0, y0, a, b);
    cplx z[4];
    roots(E, 1.0, z);
    const double sc = 1.0 + (std::fabs(x0) + a) * (std::fabs(x0) + a)
                      + (std::fabs(y0) + b) * (std::fabs(y0) + b);
    double phi[4];
    bool valid[4];
    for (int i = 0; i < 4; ++i) {
        const bool cand = std::fabs(std::abs(z[i]) - 1.0) < Z_TOL;
        double ph = cand ? std::arg(z[i]) : 0.0, g, dg;
        g_dg(ph, x0, y0, a, b, g, dg);
        for (int it = 0; it < 3; ++it) {
            const double trial = ph - (dg != 0.0 ? g / dg : 0.0);
            double gt, dgt;
            g_dg(trial, x0, y0, a, b, gt, dgt);
            if (std::fabs(gt) < std::fabs(g)) {
                ph = trial;
                g = gt;
                dg = dgt;
            }
        }
        valid[i] = cand && std::fabs(g) <= G_TOL * sc;
        phi[i] = mod2pi(ph);
    }
    bool drop[4] = {false, false, false, false};
    for (int i = 0; i < 4; ++i)
        for (int j = i + 1; j < 4; ++j) {
            const double d = std::fabs(mod2pi(phi[i] - phi[j] + PI) - PI);
            if (valid[i] && valid[j] && d < PAIR_TOL) drop[i] = drop[j] = true;
        }
    double keep[4];
    int n = 0;
    for (int i = 0; i < 4; ++i) {              // insertion sort, ascending
        if (!valid[i] || drop[i]) continue;
        int j = n++;
        while (j > 0 && keep[j - 1] > phi[i]) {
            keep[j] = keep[j - 1];
            --j;
        }
        keep[j] = phi[i];
    }
    phi_a = n > 0 ? keep[0] : 0.0;
    phi_b = n > 1 ? keep[1] : 0.0;
    return n;
}

// the ellipse arc [lo, hi] inside the star and the length dth of the limb
// arc inside the ellipse, for two crossings. The ellipse arc is decided at
// the midpoint of the longer of its two arcs; the limb arc inside the
// ellipse is always the shorter one (the planet lies within radius A < 1).
inline void arcs(double x0, double y0, double a, double b, double phi_a,
                 double phi_b, double& lo, double& hi, double& dth) {
    const bool long_first = (phi_b - phi_a) >= PI;
    const double mid = long_first ? 0.5 * (phi_a + phi_b)
                                  : 0.5 * (phi_a + phi_b) + PI;
    const double xm = x0 + a * std::cos(mid), ym = y0 + b * std::sin(mid);
    const bool mid_in = xm * xm + ym * ym < 1.0;
    const bool first = long_first ? mid_in : !mid_in;   // [phi_a, phi_b] inside
    lo = first ? phi_a : phi_b;
    hi = first ? phi_b : phi_a + TWO_PI;
    const double ta = std::atan2(y0 + b * std::sin(phi_a), x0 + a * std::cos(phi_a));
    const double tb = std::atan2(y0 + b * std::sin(phi_b), x0 + a * std::cos(phi_b));
    const double dt = std::fabs(mod2pi(ta) - mod2pi(tb));
    dth = std::min(dt, TWO_PI - dt);
}

// ---- even terms: Fourier coefficients of h_n(s) K ---------------------------

// q[n][m], n = 0..2, m = 0..5: h_n(s) K = Re sum_m q_m e^{i m phi}, with
// h_n(s) = sum_p alpha[n][p] s^p, alpha[n][p] = (-1)^p C(n, p) / (2 (p + 1))
inline void q_coeffs(const Ellipse& E, cplx q[3][6]) {
    static const double alpha[3][3] = {
        {0.5, 0.0, 0.0}, {0.5, -0.25, 0.0}, {0.5, -0.5, 1.0 / 6.0}};
    const int H = 5, W = 11;
    cplx T[W], Tn[W];
    for (int i = 0; i < W; ++i) T[i] = 0.0;
    T[H - 1] = std::conj(E.K1);
    T[H] = E.K0;
    T[H + 1] = E.K1;
    const cplx Sk[5] = {E.S2, std::conj(E.S1), E.S0, E.S1, E.S2};   // j = -2..2
    for (int n = 0; n < 3; ++n)
        for (int m = 0; m < 6; ++m) q[n][m] = 0.0;
    for (int p = 0; p < 3; ++p) {
        if (p > 0) {                           // T <- S * T
            for (int i = 0; i < W; ++i) {
                Tn[i] = 0.0;
                for (int jj = 0; jj < 5; ++jj) {
                    const int src = i - (jj - 2);
                    if (src >= 0 && src < W) Tn[i] += Sk[jj] * T[src];
                }
            }
            for (int i = 0; i < W; ++i) T[i] = Tn[i];
        }
        for (int n = p; n < 3; ++n)
            for (int m = 0; m < 6; ++m) q[n][m] += alpha[n][p] * T[H + m];
    }
}

// Psi_n(hi) - Psi_n(lo), Psi_n the exact antiderivative, in difference form
inline double even_arc(const cplx qn[6], double lo, double hi) {
    const double mid = 0.5 * (lo + hi), half = 0.5 * (hi - lo);
    double acc = qn[0].real() * (hi - lo);
    for (int m = 1; m < 6; ++m)
        acc += (4.0 / m) * (qn[m] * std::polar(1.0, m * mid)).real()
               * std::sin(m * half);
    return acc;
}

// ---- poles: partial fractions over the roots of D ---------------------------

// Newton steps on (sigma, pi) for the quadratic factor z^2 - sigma z + pi
inline void bairstow(const Ellipse& E, double p, cplx& sig, cplx& pi_) {
    const cplx dc[5] = {E.S2, std::conj(E.S1), E.S0 - p, E.S1, E.S2};  // low->high
    for (int it = 0; it < N_BAIRSTOW; ++it) {
        cplx al = 0.0, be = 1.0;               // z^k mod q = al z + be
        cplx das = 0.0, dbs = 0.0, dap = 0.0, dbp = 0.0;
        cplx r1 = dc[0] * al, r0 = dc[0] * be;
        cplx J11 = 0.0, J12 = 0.0, J21 = 0.0, J22 = 0.0;
        for (int k = 1; k < 5; ++k) {
            const cplx nal = al * sig + be, nbe = -al * pi_;
            const cplx ndas = das * sig + al + dbs, ndbs = -das * pi_;
            const cplx ndap = dap * sig + dbp, ndbp = -dap * pi_ - al;
            al = nal; be = nbe; das = ndas; dbs = ndbs; dap = ndap; dbp = ndbp;
            r1 += dc[k] * al;
            r0 += dc[k] * be;
            J11 += dc[k] * das; J12 += dc[k] * dap;
            J21 += dc[k] * dbs; J22 += dc[k] * dbp;
        }
        const cplx det = J11 * J22 - J12 * J21;
        if (det == 0.0) break;
        sig -= (J22 * r1 - J12 * r0) / det;
        pi_ -= (-J21 * r1 + J11 * r0) / det;
    }
}

// for the quadratic factor q of D, with N = aN z + bN and Q = D/q = aQ z + bQ
// (mod q): the sum of N/D' over its two roots (A_sum) and the C of
// int (A z + B)/q dz (C_num, before the factor i); symmetric in the roots
inline void pair_terms(const Ellipse& E, double p, cplx sig, cplx pi_,
                       cplx& A_sum, cplx& C_num) {
    const cplx Q2 = E.S2;
    const cplx Q1 = E.S1 + sig * Q2;
    const cplx Q0 = sig * Q1 + (E.S0 - p) - pi_ * Q2;
    const cplx aN = E.K1 * sig + E.K0, bN = std::conj(E.K1) - E.K1 * pi_;
    const cplx aQ = Q2 * sig + Q1, bQ = Q0 - Q2 * pi_;
    cplx den = aQ * aQ * pi_ + aQ * bQ * sig + bQ * bQ;
    if (den == 0.0) den = 1.0;
    A_sum = (aN * bQ - bN * aQ) / den;
    C_num = 0.5 * (2.0 * aN * aQ * pi_ + (aN * bQ + bN * aQ) * sig
                   + 2.0 * bN * bQ) / den;
}

// a whole ellipse on the disc: -(pi/p) Re sum_{|z_r| < 1} N/D'(z_r), the two
// inner roots summed as one quadratic factor
inline double pole_inside(const Ellipse& E, double p, const cplx z[4]) {
    cplx sig = 0.0, pi_ = 1.0;
    for (int i = 0; i < 4; ++i)
        if (std::abs(z[i]) < 1.0) {
            sig += z[i];
            pi_ *= z[i];
        }
    bairstow(E, p, sig, pi_);
    cplx A_sum, C_num;
    pair_terms(E, p, sig, pi_, A_sum, C_num);
    return -PI * A_sum.real() / p;
}

// change of log(e^{i phi} - z) for phi from lo to hi, continuous on the arc
inline cplx dlog(cplx z, double lo, double hi, cplx w1, cplx w2) {
    const double dm = std::log(std::abs(w2 - z)) - std::log(std::abs(w1 - z));
    double da;
    if (std::abs(z) < 1.0)
        da = (hi - lo) + std::arg(1.0 - z / w2) - std::arg(1.0 - z / w1);
    else
        da = std::arg(1.0 - w2 / z) - std::arg(1.0 - w1 / z);
    return cplx(dm, da);
}

// int du / (u^2 - Delta) = -(1/u) sum_k (Delta/u^2)^k / (2k + 1)
inline cplx Jser(cplx u, cplx Delta) {
    const cplx x = Delta / (u * u);
    cplx acc = 0.0;
    for (int k = N_SERIES - 1; k >= 0; --k) acc = acc * x + 1.0 / (2.0 * k + 1.0);
    return -acc / u;
}

// (1/2p) int_lo^hi K / (p - s) dphi along one ellipse arc inside the star:
// (1/2p) Re sum_r R_r [log(e^{i phi} - z_r)], R_r = -N(z_r) / (i D'(z_r))
inline double pole_arc(const Ellipse& E, double p, const cplx z[4], double lo,
                       double hi) {
    const cplx I(0.0, 1.0);
    const cplx w1 = std::polar(1.0, lo), w2 = std::polar(1.0, hi);
    // near-double pairs: up to two disjoint, scored by |Delta| / d^2, d the
    // distance from the pair's centre to the arc
    bool used[4] = {false, false, false, false};
    int pj[2], pl[2];
    bool pgood[2];
    for (int round = 0; round < 2; ++round) {
        double best = std::numeric_limits<double>::infinity();
        int bi = 0;
        for (int m = 0; m < 6; ++m) {
            const int j = PAIRS[m][0], l = PAIRS[m][1];
            if (used[j] || used[l]) continue;
            const cplx Dl = 0.25 * (z[j] - z[l]) * (z[j] - z[l]);
            const cplx c = 0.5 * (z[j] + z[l]);
            const double ang = mod2pi(std::arg(c));
            const bool on = (ang >= lo && ang <= hi)
                            || (ang + TWO_PI >= lo && ang + TWO_PI <= hi);
            const double d = on ? std::fabs(std::abs(c) - 1.0)
                                : std::min(std::abs(w1 - c), std::abs(w2 - c));
            const double score = std::abs(Dl) / std::max(d * d, 1e-300);
            if (score < best) {
                best = score;
                bi = m;
            }
        }
        pj[round] = PAIRS[bi][0];
        pl[round] = PAIRS[bi][1];
        pgood[round] = best <= PAIR_RATIO;
        if (pgood[round]) used[pj[round]] = used[pl[round]] = true;
    }

    cplx ell = 0.0;
    // isolated roots; one beyond |z| = 2 is taken through its partner
    // zeta = 1/conj(z) inside the disc, where R(z) = conj(R(zeta)) and the
    // log's change is that of log(1 - e^{i phi} conj(zeta))
    for (int k = 0; k < 4; ++k) {
        if (used[k]) continue;
        const double a2 = std::norm(z[k]);
        const bool far = a2 > 4.0;
        cplx zeta = far ? z[k] / a2 : z[k];
        const cplx nw = zeta - E.D(zeta, p) / E.dD(zeta, p);
        if (finite(nw) && std::abs(E.D(nw, p)) < std::abs(E.D(zeta, p))) zeta = nw;
        const cplx dD = E.dD(zeta, p);
        if (dD == 0.0) continue;
        const cplx R = -E.N(zeta) / (I * dD);
        if (far) {
            const cplx b2 = 1.0 - w2 * std::conj(zeta), b1 = 1.0 - w1 * std::conj(zeta);
            const cplx dlw(std::log(std::abs(b2)) - std::log(std::abs(b1)),
                           std::arg(b2) - std::arg(b1));
            ell += std::conj(R) * dlw;
        } else {
            ell += R * dlog(zeta, lo, hi, w1, w2);
        }
    }
    // near-double pairs, each as one quadratic factor q = z^2 - sigma z + pi:
    // int (A z + B)/q dz = (A/2) log q + C J(z - sigma/2), the winding of
    // log q taken from the two roots' own continued logs
    for (int round = 0; round < 2; ++round) {
        if (!pgood[round]) continue;
        const cplx z1 = z[pj[round]], z2 = z[pl[round]];
        cplx sig = z1 + z2, pi_ = z1 * z2;
        bairstow(E, p, sig, pi_);
        cplx A_sum, C_num;
        pair_terms(E, p, sig, pi_, A_sum, C_num);
        const cplx Acoef = I * A_sum, Ccoef = I * C_num;
        const cplx qh = w2 * w2 - sig * w2 + pi_;
        const cplx ql = w1 * w1 - sig * w1 + pi_;
        const double darg = std::arg(qh / ql);
        const double rough = dlog(z1, lo, hi, w1, w2).imag()
                             + dlog(z2, lo, hi, w1, w2).imag();
        const double wind = std::round((rough - darg) / TWO_PI);
        const cplx LQ(std::log(std::abs(qh)) - std::log(std::abs(ql)),
                      darg + TWO_PI * wind);
        const cplx Delta = 0.25 * sig * sig - pi_;
        const cplx cen = 0.5 * sig;
        const cplx Jd = Jser(w2 - cen, Delta) - Jser(w1 - cen, Delta);
        ell += 0.5 * Acoef * LQ + Ccoef * Jd;
    }
    return ell.real() / (2.0 * p);
}

// occulted flux of [mu^0, mu^2, mu^4, P_eps...] for the ellipse with centre
// (x0, y0) in its principal frame and semi-axes a > b
inline void ellipse_occ(double x0, double y0, double a, double b,
                        const LawData& L, double* occ) {
    for (int k = 0; k < 3 + L.K; ++k) occ[k] = 0.0;
    const double d = std::hypot(x0, y0);
    const bool fast_in = d + a < 1.0;
    const bool general = !fast_in && (d - a < 1.0);
    if (!fast_in && !general) return;              // disjoint
    int cnt = 0;
    double phi_a = 0.0, phi_b = 0.0;
    if (general) cnt = crossings(x0, y0, a, b, phi_a, phi_b);
    const bool partial = general && cnt == 2;
    const bool inside = fast_in || (general && cnt != 2 && d < 1.0);
    if (!partial && !inside) return;

    const Ellipse E(x0, y0, a, b);
    cplx q[3][6];
    q_coeffs(E, q);
    if (inside) {
        for (int n = 0; n < 3; ++n) occ[n] = TWO_PI * q[n][0].real();
        for (int k = 0; k < L.K; ++k) {
            const double p = 1.0 + L.eps[k];
            cplx z[4];
            roots(E, p, z);
            occ[3 + k] = pole_inside(E, p, z);
        }
        return;
    }
    double lo, hi, dth;
    arcs(x0, y0, a, b, phi_a, phi_b, lo, hi, dth);
    for (int n = 0; n < 3; ++n)
        occ[n] = even_arc(q[n], lo, hi) + dth / (2.0 * (n + 1));
    for (int k = 0; k < L.K; ++k) {
        const double e = L.eps[k], p = 1.0 + e;
        cplx z[4];
        roots(E, p, z);
        occ[3 + k] = pole_arc(E, p, z, lo, hi) + dth / (2.0 * p * e);
    }
}

