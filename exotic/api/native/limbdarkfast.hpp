// number of shape weights a law takes: 2, 4 or 5
inline int n_weights(Law law) { return detail::law_data(law).n_w; }

// "hybrid2", "hybrid4" or "hybrid5" -> Law
inline Law law_from_name(const std::string& name) {
    if (name == "hybrid2") return Law::hybrid2;
    if (name == "hybrid4") return Law::hybrid4;
    if (name == "hybrid5") return Law::hybrid5;
    throw std::invalid_argument("limbdarkfast: unknown law '" + name +
                                "'; expected hybrid2, hybrid4 or hybrid5");
}

// I(mu) / I(1) = 1 - sum_j w_j S_j(mu)
inline double intensity(double mu, const double* w, Law law) {
    const detail::LawData& L = detail::law_data(law);
    const double m2 = mu * mu;
    double gen[6] = {1.0, m2, m2 * m2, 0.0, 0.0, 0.0};
    for (int k = 0; k < L.K; ++k) gen[3 + k] = 1.0 / ((m2 + L.eps[k]) * (m2 + L.eps[k]));
    double I = 1.0;
    for (int j = 0; j < L.n_w; ++j) {
        double s = 0.0;
        for (int k = 0; k < 3 + L.K; ++k) s += L.G[j][k] * gen[k];
        I -= w[j] * s;
    }
    return I;
}

// Normalised flux of a star with a hybrid law, occulted by a spherical
// planet of radius r (stellar radii) at sky separation z. w points to the
// law's n_weights(law) shape weights. Exact for r < 1; for a companion
// larger than the star the even terms lose about r^5 x 1e-16 (tested to
// r = 2; 2e-12 at r = 10, 2e-7 at r = 100).
inline double hybrid_flux(double z, double r, const double* w, Law law) {
    if (!(r >= 0.0)) throw std::domain_error("limbdarkfast: need r >= 0");
    const detail::LawData& L = detail::law_data(law);
    double occ[6];
    detail::sphere_occ(z, r, L, occ);
    return detail::flux_from_occ(occ, w, L);
}

// Normalised flux of a star with a hybrid law, occulted by an oblate
// planet: sky position (X, Y), X along its direction of motion;
// area-equivalent radius r = sqrt(A B), with A = r / sqrt(1 - f) and
// B = A (1 - f); flattening f in [0, 1); long axis at angle theta (radians)
// from X. Requires r <= (1 - f)^(3/2).
inline double hybrid_flux_oblate(double X, double Y, double r, double f,
                                 double theta, const double* w, Law law) {
    if (!(f >= 0.0 && f < 1.0))
        throw std::domain_error("limbdarkfast: need 0 <= f < 1");
    if (!(r >= 0.0 && r <= std::pow(1.0 - f, 1.5) * (1.0 + 1e-12)))
        throw std::domain_error("limbdarkfast: need 0 <= r <= (1 - f)^(3/2): the "
                                "planet must cross the stellar limb at most twice");
    const detail::LawData& L = detail::law_data(law);
    const double c = std::cos(theta), s = std::sin(theta);
    const double x0 = X * c + Y * s, y0 = -X * s + Y * c;   // principal frame
    double occ[6];
    if (f < detail::F_SW) {
        detail::sphere_occ(std::hypot(x0, y0), r, L, occ);
    } else {
        const double a = r / std::sqrt(1.0 - f);
        detail::ellipse_occ(x0, y0, a, a * (1.0 - f), L, occ);
    }
    return detail::flux_from_occ(occ, w, L);
}

// --- std::vector conveniences: the weights' count is checked ---------------

inline void check_weights(const std::vector<double>& w, Law law) {
    if (static_cast<int>(w.size()) != n_weights(law))
        throw std::invalid_argument("limbdarkfast: wrong number of weights for this law");
}

inline double hybrid_flux(double z, double r, const std::vector<double>& w, Law law) {
    check_weights(w, law);
    return hybrid_flux(z, r, w.data(), law);
}

inline double hybrid_flux_oblate(double X, double Y, double r, double f,
                                 double theta, const std::vector<double>& w,
                                 Law law) {
    check_weights(w, law);
    return hybrid_flux_oblate(X, Y, r, f, theta, w.data(), law);
}

// a light curve: one flux per separation
inline std::vector<double> hybrid_flux(const std::vector<double>& z, double r,
                                       const std::vector<double>& w, Law law) {
    check_weights(w, law);
    std::vector<double> F(z.size());
    for (std::size_t i = 0; i < z.size(); ++i) F[i] = hybrid_flux(z[i], r, w.data(), law);
    return F;
}

// a light curve: one flux per sky position
inline std::vector<double> hybrid_flux_oblate(const std::vector<double>& X,
                                              const std::vector<double>& Y,
                                              double r, double f, double theta,
                                              const std::vector<double>& w,
                                              Law law) {
    check_weights(w, law);
    if (X.size() != Y.size())
        throw std::invalid_argument("limbdarkfast: X and Y differ in length");
    std::vector<double> F(X.size());
    for (std::size_t i = 0; i < X.size(); ++i)
        F[i] = hybrid_flux_oblate(X[i], Y[i], r, f, theta, w.data(), law);
    return F;
}

